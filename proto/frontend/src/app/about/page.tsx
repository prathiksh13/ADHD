function Section({
  label,
  title,
  lead,
  children,
  tone = "canvas",
}: {
  label: string;
  title: string;
  lead: string;
  children: React.ReactNode;
  tone?: "canvas" | "surface";
}) {
  return (
    <section className={tone === "surface" ? "border-y border-line bg-surface" : "border-b border-line"}>
      <div className="mx-auto max-w-6xl px-6 py-16">
        <div className="max-w-3xl">
          <p className="section-label">{label}</p>
          <h2 className="mt-2 text-2xl font-semibold tracking-tight text-balance text-ink sm:text-[26px]">
            {title}
          </h2>
          <p className="mt-3 text-[15px] leading-relaxed text-ink-muted">{lead}</p>
        </div>
        <div className="mt-8">{children}</div>
      </div>
    </section>
  );
}

function Prose({ children }: { children: React.ReactNode }) {
  return <div className="max-w-3xl flex flex-col gap-3.5">{children}</div>;
}

function Mini({
  icon: Icon,
  title,
  value,
  body,
}: {
  icon: React.ComponentType<{ className?: string }>;
  title: string;
  value: string;
  body: string;
}) {
  return (
    <div className="rounded-lg border border-line bg-canvas p-5">
      <div className="flex items-center gap-2">
        <Icon className="size-4 text-primary-700" />
        <p className="text-[12px] font-semibold text-ink">{title}</p>
      </div>
      <p className="mt-2.5 text-[15px] font-semibold text-ink tabular-nums">{value}</p>
      <p className="mt-1.5 text-[12.5px] leading-relaxed text-ink-muted">{body}</p>
    </div>
  );
}

function ModelBlock({
  title,
  body,
  accent,
}: {
  title: string;
  body: string;
  accent: "primary" | "secondary" | "accent";
}) {
  const tones = {
    primary: "border-primary-300 bg-primary-50/40",
    secondary: "border-secondary-200 bg-secondary-50/50",
    accent: "border-accent-200 bg-accent-50/50",
  };
  const dots = {
    primary: "bg-primary-600",
    secondary: "bg-secondary-500",
    accent: "bg-accent-500",
  };

  return (
    <div className={cn(tones[accent], "rounded-lg border p-5")}>
      <div className="flex items-center gap-2">
        <span className={cn("size-1.5 rounded-full", dots[accent])} />
        <h3 className="text-[15px] font-semibold tracking-tight text-ink">{title}</h3>
      </div>
      <p className="mt-2.5 text-[13.5px] leading-relaxed text-ink-muted">{body}</p>
    </div>
  );
}

function ViewCard({ title, body }: { title: string; body: string }) {
  return (
    <div className="rounded-lg border border-line bg-canvas p-4">
      <p className="text-[13.5px] font-semibold text-ink">{title}</p>
      <p className="mt-1 text-[12.5px] leading-relaxed text-ink-muted">{body}</p>
    </div>
  );
}
